/**
 * 描いた本文と生テキストの位置の対応。
 *
 * markdown を見せる面は、**どの面もこの2つを実装する**（`openspec/specs/markdown/module`
 * の「描いた本文と生テキストの位置の対応を公開する」）。整形された本文の面も、生テキストの
 * 面も、図に添えた生テキストも同じである。
 *
 * **面ごとに注釈の実装を持たないためにこれが在る。** 注釈の側はこれだけを見て、
 * 自分がどの面に載っているかを分岐しない。面が増えても注釈は変わらない。
 *
 * 位置は文字数で表す。整形された本文の上の位置や要素の順番など、描き方に依存する
 * 表し方をしない。
 *
 * ## 何の先頭から数えるか
 *
 * **面に渡した文字列の先頭からである。** ディスク上の元のファイルではない
 * （`openspec/specs/markdown/module` の「位置は面に渡された文字列の先頭を基準とする」）。
 *
 * **揃えてから渡す必要はない。面が自分で吸収する。**
 *
 * 整形された本文の面は `parseMarkdown` を通り、あれは解析の前に **CRLF を LF へ潰し、
 * front matter を落とす**。面の中に出る位置の印はその後の文字列を指すので、渡された
 * 文字列とは基準が割れる。その食い違いを面の内側で写像し、答えるときは渡された文字列の
 * 基準へ戻す（`./normalize.ts`。`openspec/specs/markdown/module` の「面は解析のための
 * 正規化を自分で吸収する」）。
 *
 * **揃える手続きを呼ぶ側に課さない。** 揃え忘れは実行時に何の合図も出さず、誤った位置が
 * 返るだけになる。かつては呼ぶ側の責任にしており、本文の `b` を選ぶと front matter の
 * `b` が返る反例が実在した。
 *
 * **面は渡された文字列そのものを作り変えない。** 作り変えるのは位置を突き合わせるための
 * 内部の写しだけで、表示にも、面を通って外へ出ていく文字列にも波及しない。
 *
 * 写像が作れないときは両方向とも `null` を返す。**恒等で代用しない。**
 */

/** 生テキストの範囲。`start` は含み、`end` は含まない */
export interface SourceRange {
  start: number;
  end: number;
}

/**
 * 面が実装する位置の対応。
 *
 * 両方向とも、対応が取れない場合は `null` を返す。**取れないことを黙って通さない。**
 * 対応の取れない領域（行の並びが崩れたコードブロック、図として描かれた箇所）は
 * 呼ぶ側が別の見せ方に倒す必要があり、その判断のために `null` が要る。
 */
export interface PositionPort {
  /**
   * DOM の選択範囲 → 生テキストの位置。
   *
   * 範囲が要素をまたいでいてもよい（強調・リンク・段落の境界）。生テキストの上では
   * 連続した1つの範囲になる。
   */
  toSourceRange(range: Range): SourceRange | null;

  /**
   * 生テキストの位置 → DOM の範囲。
   *
   * 塗り（CSS Custom Highlight API）に渡すために要る。
   */
  toDomRange(source: SourceRange): Range | null;
}
